// Converts the hackathon CSVs into typed app data and trains the lead propensity model.
// Run with: pnpm data
import fs from 'node:fs';
import path from 'node:path';

const SRC = 'YTL_TrackA_Udyam_Digital_Data';
const OUT = 'src/data/generated';
fs.mkdirSync(OUT, { recursive: true });

function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}
const read = (f) => parseCsv(fs.readFileSync(path.join(SRC, f), 'utf8'));
const writeTs = (name, exportName, value, type, typeImport) =>
  fs.writeFileSync(path.join(OUT, name), `// Generated by scripts/build-data.mjs. Do not edit by hand.\n${typeImport ? `import type { ${typeImport} } from '../../lib/types.ts';\n` : ''}export const ${exportName}${type ? `: ${type}` : ''} = ${JSON.stringify(value, null, 1)};\n`);

// Catalogue
const products = read('product_catalogue.csv').map((p) => ({
  id: p.product_id,
  category: p.category,
  name: p.product_name,
  description: p.description,
  unit: p.unit,
  priceMin: Number(p.price_min_inr_per_month),
  priceMax: Number(p.price_max_inr_per_month),
  setupFee: Number(p.one_time_setup_inr),
  minContractMonths: Number(p.min_contract_months),
  tiers: p.available_city_tiers.split(';').map(Number),
  minEmployees: Number(p.min_employees),
  minSites: Number(p.min_sites),
  requiresGstin: p.requires_gstin === 'Y',
  requiresOneOf: p.requires_one_of ? p.requires_one_of.split('|') : [],
  installDays: Number(p.typical_install_days),
  segments: p.target_segments.split(';'),
}));
writeTs('products.ts', 'PRODUCTS', products, 'Product[]', 'Product');

// Registries (server-only JSON)
const gst = read('mock_gstin_registry.csv').map((r) => ({
  gstin: r.gstin, legalName: r.legal_name, tradeName: r.trade_name, constitution: r.constitution,
  address: r.principal_place_of_business, state: r.state, registrationDate: r.registration_date, status: r.status,
}));
fs.writeFileSync(path.join(OUT, 'gstin-registry.json'), JSON.stringify(gst));
const udyam = read('mock_udyam_registry.csv').map((r) => ({
  udyamNumber: r.udyam_number, enterpriseName: r.enterprise_name, enterpriseType: r.enterprise_type,
  majorActivity: r.major_activity, nicDescription: r.nic_description, state: r.state, city: r.city,
  registrationDate: r.date_of_registration,
}));
fs.writeFileSync(path.join(OUT, 'udyam-registry.json'), JSON.stringify(udyam));

// Leads
const leads = read('smb_leads.csv');
const cities = {};
for (const l of leads) cities[l.city] = { tier: Number(l.city_tier), state: l.state };
writeTs('cities.ts', 'CITIES', cities, 'Record<string, { tier: number; state: string }>');

const SEG = { 'Micro retail & services': 'micro', 'Professional offices': 'prof', 'Small multi-site businesses': 'multi', 'Small manufacturers': 'mfg' };
const businessTypes = {};
for (const l of leads) businessTypes[l.business_type] = SEG[l.segment];
writeTs('business-types.ts', 'BUSINESS_TYPES', businessTypes, 'Record<string, Segment>', 'Segment');

// Analytics
const STAGES = ['Lead', 'Contacted', 'Needs assessed', 'Quote accepted', 'KYC complete', 'Activated'];
const stageIdx = (s) => STAGES.indexOf(s);
const funnel = STAGES.map((s, i) => ({ stage: s, count: leads.filter((l) => stageIdx(l.stage_reached) >= i).length }));
const ADDRESSABLE = {
  'Owner had no time for a visit': 'Field-visit scheduling', 'Visit not scheduled by sales': 'Field-visit scheduling',
  'Quote too complex to understand': 'Complex or slow quotes', 'Quote took too long to arrive': 'Complex or slow quotes',
  'Missing GST or Udyam document': 'Paperwork delays', 'Found paperwork too long': 'Paperwork delays', 'Authorised signatory not available': 'Paperwork delays',
  'Installation delayed beyond 21 days': 'Install delays',
};
const dropCounts = {};
for (const l of leads) if (l.drop_reason) dropCounts[l.drop_reason] = (dropCounts[l.drop_reason] || 0) + 1;
const dropReasons = Object.entries(dropCounts).sort((a, b) => b[1] - a[1]).map(([reason, count]) => ({ reason, count, module: ADDRESSABLE[reason] ?? null }));
const group = (key) => {
  const m = {};
  for (const l of leads) {
    const k = l[key]; m[k] ??= { key: k, leads: 0, activated: 0, value: 0, churned: 0, nps: 0, npsN: 0, cac: 0 };
    const g = m[k]; g.leads++; g.cac += Number(l.acquisition_cost_inr || 0);
    if (l.outcome === 'Activated') { g.activated++; g.value += Number(l.monthly_bundle_value_inr || 0); if (l.churned_within_6_months === 'Y') g.churned++; if (l.nps_score) { g.nps += Number(l.nps_score); g.npsN++; } }
  }
  return Object.values(m).map((g) => ({ key: g.key, leads: g.leads, activated: g.activated, rate: g.activated / g.leads,
    avgBundle: g.activated ? Math.round(g.value / g.activated) : 0, churn: g.activated ? g.churned / g.activated : 0,
    nps: g.npsN ? +(g.nps / g.npsN).toFixed(1) : null, cacPerActivation: g.activated ? Math.round(g.cac / g.activated) : null }))
    .sort((a, b) => b.leads - a.leads);
};
const act = leads.filter((l) => l.outcome === 'Activated');
const median = (a) => { const s = [...a].sort((x, y) => x - y); return s.length ? s[Math.floor(s.length / 2)] : 0; };
const analytics = {
  totalLeads: leads.length,
  activated: act.length,
  activationRate: act.length / leads.length,
  avgDaysToActivate: +(act.reduce((s, l) => s + Number(l.days_lead_to_activation), 0) / act.length).toFixed(1),
  avgChaseCalls: +(act.reduce((s, l) => s + Number(l.customer_follow_up_calls), 0) / act.length).toFixed(1),
  cacPerActivation: Math.round(leads.reduce((s, l) => s + Number(l.acquisition_cost_inr || 0), 0) / act.length),
  medianBundle: median(act.map((l) => Number(l.monthly_bundle_value_inr))),
  churn6m: act.filter((l) => l.churned_within_6_months === 'Y').length / act.length,
  funnel, dropReasons,
  addressable: Object.entries(dropReasons.reduce((m, d) => { if (d.module) m[d.module] = (m[d.module] || 0) + d.count; return m; }, {})).map(([module, count]) => ({ module, count })),
  bySegment: group('segment'), bySource: group('lead_source'), byGstin: group('has_gstin'), byTier: group('city_tier'), byLanguage: group('preferred_language'),
};

// Propensity model: logistic regression on features known at lead creation (no stage/outcome leakage).
const CATS = {
  segment: Object.keys(SEG), lead_source: [...new Set(leads.map((l) => l.lead_source))],
  current_internet: [...new Set(leads.map((l) => l.current_internet))], annual_turnover_band: [...new Set(leads.map((l) => l.annual_turnover_band))],
  current_provider: [...new Set(leads.map((l) => l.current_provider))],
};
const featureNames = ['bias', 'has_gstin', 'has_udyam', 'tier1', 'log_employees', 'multi_site', 'log_spend', 'n_products',
  ...Object.entries(CATS).flatMap(([k, vs]) => vs.slice(1).map((v) => `${k}=${v}`))];
function featurize(l) {
  const x = [1, l.has_gstin === 'Y' ? 1 : 0, l.has_udyam === 'Y' ? 1 : 0, l.city_tier === '1' ? 1 : 0,
    Math.log1p(Number(l.employee_count)) / 4, Number(l.num_sites) > 1 ? 1 : 0, Math.log1p(Number(l.monthly_telecom_spend_inr || 0)) / 10,
    (l.products_of_interest ? l.products_of_interest.split(';').length : 0) / 5];
  for (const [k, vs] of Object.entries(CATS)) for (const v of vs.slice(1)) x.push(l[k] === v ? 1 : 0);
  return x;
}
let seed = 42; const rand = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
const data = leads.map((l) => ({ x: featurize(l), y: l.outcome === 'Activated' ? 1 : 0, r: rand() }));
const train = data.filter((d) => d.r < 0.8), test = data.filter((d) => d.r >= 0.8);
const w = new Array(featureNames.length).fill(0);
const sig = (z) => 1 / (1 + Math.exp(-z));
const dot = (a, b) => a.reduce((s, v, i) => s + v * b[i], 0);
for (let epoch = 0; epoch < 600; epoch++) {
  const g = new Array(w.length).fill(0);
  for (const d of train) { const e = sig(dot(w, d.x)) - d.y; d.x.forEach((v, i) => (g[i] += e * v)); }
  w.forEach((_, i) => (w[i] -= (0.8 * (g[i] / train.length + (i ? 0.001 * w[i] : 0)))));
}
function auc(set) {
  const s = set.map((d) => ({ p: sig(dot(w, d.x)), y: d.y })).sort((a, b) => a.p - b.p);
  let rank = 0, pos = 0, neg = 0; s.forEach((d, i) => { if (d.y) { rank += i + 1; pos++; } else neg++; });
  return (rank - (pos * (pos + 1)) / 2) / (pos * neg);
}
const testAuc = +auc(test).toFixed(3);
// Lift: activation rate in top-scored 20% of the held-out set vs overall.
const ranked = test.map((d) => ({ p: sig(dot(w, d.x)), y: d.y })).sort((a, b) => b.p - a.p);
const top = ranked.slice(0, Math.round(ranked.length * 0.2));
const model = { featureNames, weights: w.map((v) => +v.toFixed(5)), categories: CATS, testAuc,
  trainSize: train.length, testSize: test.length,
  topQuintileRate: +(top.filter((d) => d.y).length / top.length).toFixed(3), baseRate: +(test.filter((d) => d.y).length / test.length).toFixed(3) };
writeTs('model.ts', 'PROPENSITY_MODEL', model);
writeTs('analytics.ts', 'ANALYTICS', analytics);

// Call list: dropped leads that reached at least "Contacted", scored, with masked contact data.
const mask = (s, keep = 4) => (s ? s.slice(0, 2) + '•'.repeat(Math.max(0, s.length - 2 - keep)) + s.slice(-keep) : '');
const callList = leads.filter((l) => l.outcome === 'Dropped').map((l) => ({
  id: l.lead_id, business: l.business_name, type: l.business_type, segment: SEG[l.segment], city: l.city, tier: Number(l.city_tier),
  language: l.preferred_language, employees: Number(l.employee_count), sites: Number(l.num_sites), gstin: l.has_gstin === 'Y',
  gstinMasked: mask(l.gstin), source: l.lead_source, stage: l.stage_reached, dropReason: l.drop_reason, interest: l.products_of_interest,
  contact: l.contact_name, role: l.contact_role, spend: Number(l.monthly_telecom_spend_inr || 0),
  score: +sig(dot(w, featurize(l))).toFixed(4), module: ADDRESSABLE[l.drop_reason] ?? null,
})).sort((a, b) => b.score - a.score);
fs.writeFileSync(path.join(OUT, 'call-list.json'), JSON.stringify(callList));
console.log(`products ${products.length}, gstin ${gst.length}, udyam ${udyam.length}, cities ${Object.keys(cities).length}, call list ${callList.length}`);
console.log(`model AUC ${testAuc}, top-quintile activation ${model.topQuintileRate} vs base ${model.baseRate}`);
console.log('addressable', analytics.addressable, 'activation', analytics.activationRate, 'cac', analytics.cacPerActivation, 'median', analytics.medianBundle);
